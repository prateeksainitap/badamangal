/**
 * Pre-renders the fixed Hindi strings used in the share images
 * (opengraph-image.tsx routes) into small PNG wordmarks and writes them
 * to src/lib/og-hindi-wordmarks.generated.ts as data URLs.
 *
 * Why: next/og (Satori) has no complex text shaping for Devanagari. It
 * draws the i matra after the consonant ("मंदरि" for "मंदिर"), shows a
 * visible halant instead of conjuncts and breaks reph. Tested
 * on 1 Nov 2026 with next 15.5.18 (@vercel/og 0.7.2) and Anek Devanagari:
 * still broken. sharp renders text through Pango + HarfBuzz, which shapes
 * Devanagari correctly, so we render the Hindi here, once, and the share
 * images composite it as an <img>. Dynamic text in the images stays
 * English. A Hindi string with no wordmark here is simply left out of the
 * image (see src/lib/og-hindi.ts), so broken Hindi can never ship.
 *
 * Run after changing a temple's Hindi name or any string below:
 *   npx tsx scripts/build-og-hindi-wordmarks.ts
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import sharp from "sharp";
import { TEMPLES } from "../src/content/temples";

const SINDOOR_700 = "#9C2A2A";
const SCALE = 2; // render at 2x, displayed at 1x, for crisp edges

type Spec = {
  text: string;
  /** Display font size in px. */
  size: number;
  /** Smaller size to fall back to when the text would wrap at `size`. */
  wrapSize?: number;
  /** Display max width in px; longer text wraps onto more lines. */
  maxWidth: number;
};

const RESOURCE_TITLE = { size: 96, wrapSize: 80, maxWidth: 1000 };

const SPECS: Spec[] = [
  // Home card tagline, two lines by design.
  { text: "जहाँ भक्ति,\nवहाँ भंडारा", size: 92, maxWidth: 720 },
  // /history
  { text: "बड़ा मंगल का इतिहास", size: 78, maxWidth: 1056 },
  // /resources/aarti, /resources/chalisa
  { text: "हनुमान आरती", ...RESOURCE_TITLE },
  { text: "हनुमान चालीसा", ...RESOURCE_TITLE },
  // /resources/temples/[slug]
  ...TEMPLES.map((t) => ({ text: t.name.hi, ...RESOURCE_TITLE })),
];

async function anekDevanagariTtf(): Promise<string> {
  const dir = path.join(os.tmpdir(), "badamangal-og-fonts");
  const file = path.join(dir, "AnekDevanagari-700.ttf");
  if (existsSync(file)) return file;
  await mkdir(dir, { recursive: true });
  // A plain user agent makes Google Fonts serve TTF (Pango cannot read WOFF2).
  const css = await fetch(
    "https://fonts.googleapis.com/css2?family=Anek+Devanagari:wght@700",
    { headers: { "user-agent": "curl" } },
  ).then((r) => r.text());
  const url = css.match(/url\((https:\/\/[^)]+\.ttf)\)/)?.[1];
  if (!url) throw new Error("Anek Devanagari TTF URL not found");
  const res = await fetch(url);
  const buf = new Uint8Array((await res.arrayBuffer()) as ArrayBuffer);
  await writeFile(file, buf);
  return file;
}

function escapeMarkup(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

async function render(text: string, size: number, maxWidth: number, fontfile: string) {
  const { data, info } = await sharp({
    text: {
      text: `<span foreground="${SINDOOR_700}">${escapeMarkup(text)}</span>`,
      font: `Anek Devanagari Bold ${size * SCALE}`,
      fontfile,
      rgba: true,
      dpi: 72,
      width: maxWidth * SCALE,
      wrap: "word",
    },
  })
    .png({ palette: true, quality: 95, compressionLevel: 9, effort: 10 })
    .toBuffer({ resolveWithObject: true });
  return { data, width: info.width, height: info.height };
}

async function main() {
  const fontfile = await anekDevanagariTtf();
  const out: Record<string, { src: string; width: number; height: number }> = {};
  for (const spec of SPECS) {
    if (out[spec.text]) continue;
    let r = await render(spec.text, spec.size, spec.maxWidth, fontfile);
    if (spec.wrapSize) {
      // Wrapped if taller than a one-line render of a short probe string.
      const probe = await render("हनुमान", spec.size, spec.maxWidth, fontfile);
      if (r.height > probe.height * 1.5) {
        r = await render(spec.text, spec.wrapSize, spec.maxWidth, fontfile);
      }
    }
    out[spec.text] = {
      src: `data:image/png;base64,${r.data.toString("base64")}`,
      width: Math.round(r.width / SCALE),
      height: Math.round(r.height / SCALE),
    };
    console.log(
      `${JSON.stringify(spec.text)} ${out[spec.text].width}x${out[spec.text].height} ${(r.data.length / 1024).toFixed(1)} KB`,
    );
  }

  const target = path.join(process.cwd(), "src/lib/og-hindi-wordmarks.generated.ts");
  const body =
    `// Generated by scripts/build-og-hindi-wordmarks.ts. Do not edit by hand.\n` +
    `// Hindi strings pre-shaped with Pango + HarfBuzz (Anek Devanagari 700),\n` +
    `// because next/og cannot shape Devanagari. Values are 1x display sizes.\n\n` +
    `export const OG_HINDI_WORDMARKS: Record<string, { src: string; width: number; height: number }> = ${JSON.stringify(out, null, 2)};\n`;
  const prev = existsSync(target) ? await readFile(target, "utf8") : "";
  if (prev !== body) await writeFile(target, body);
  console.log(`wrote ${path.relative(process.cwd(), target)} (${Object.keys(out).length} wordmarks)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
