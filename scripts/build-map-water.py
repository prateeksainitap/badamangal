"""
Builds src/lib/map-water.ts: which parts of the painted map plate
(public/illustrations/v2/map-lucknow.webp) are the Gomti, its pale
banks and its bridges, so no gada is ever drawn in the river.

Run again only if the plate changes:
  magick public/illustrations/v2/map-lucknow.webp -resize 1536x1024 /tmp/plate.png
  python3 scripts/build-map-water.py /tmp/plate.png
Needs numpy, pillow and scipy.
"""
import base64, sys
import numpy as np
from PIL import Image
from scipy import ndimage as ndi

im = np.asarray(Image.open(sys.argv[1]).convert("RGB")).astype(int)
r, g, b = im[..., 0], im[..., 1], im[..., 2]

# The painted river's centre line (same trace as PAINTED_RIVER in home-map.ts).
RIVER = [[0,158],[128,166],[256,214],[384,288],[448,334],[520,384],[640,434],[760,464],[900,486],
         [1000,540],[1088,614],[1152,650],[1216,698],[1280,758],[1350,798],[1440,830],[1535,872]]

# 1. Teal water connected to the centre line.
cand = ndi.binary_closing((g >= r - 3) & (b >= r - 14) & (r < 235), iterations=2)
lab, _ = ndi.label(cand)
seeds = set()
for (x0, y0), (x1, y1) in zip(RIVER, RIVER[1:]):
    for t in np.linspace(0, 1, 40):
        x, y = int(x0 + (x1 - x0) * t), int(y0 + (y1 - y0) * t)
        if lab[y, x]:
            seeds.add(lab[y, x])
water = np.isin(lab, list(seeds))
water = ndi.binary_fill_holes(ndi.binary_opening(ndi.binary_closing(water, iterations=10), iterations=4))

# 2. Pale water at the banks, only right next to the river.
near = ndi.distance_transform_edt(~water) < 90
c2 = ndi.binary_closing(((g >= r + 2) & (b >= r - 26) & (r < 240)) & near, iterations=2) | water
lab2, _ = ndi.label(c2)
touch = set(np.unique(lab2[water])) - {0}
water = np.isin(lab2, list(touch))
water = ndi.binary_fill_holes(ndi.binary_opening(ndi.binary_closing(water, iterations=8), iterations=3))

# 3. The three painted bridges (plate px boxes).
for x0, y0, x1, y1 in [(179, 211, 339, 262), (614, 397, 819, 486), (1114, 678, 1306, 755)]:
    water[y0:y1, x0:x1] = True

# 4. 8 px cells; a cell counts as river if a third of it is water.
C = 8
H, W = water.shape
cells = water[: H // C * C, : W // C * C].reshape(H // C, C, W // C, C).mean(axis=(1, 3)) > 0.33
bits = np.packbits(cells.astype(np.uint8).ravel())
b64 = base64.b64encode(bits.tobytes()).decode()
rows, cols = cells.shape
out = f'''/**
 * Generated by scripts/build-map-water.py from the painted map plate.
 * Do not edit by hand. {cols} x {rows} cells of {C} px; 1 = the Gomti,
 * its pale banks or a bridge.
 */
export const WATER_COLS = {cols};
export const WATER_ROWS = {rows};
export const WATER_CELL_PX = {C};
export const WATER_BITS = "{b64}";
'''
open("src/lib/map-water.ts", "w").write(out)
print(cols, rows, cells.mean())
